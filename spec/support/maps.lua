--- Maps and graphs the specs build on.
--- The big ones are the maps of the examples, where the pathfinder
--- gets its real use, and where its bugs have shown up so far.
--- Tiles: 1 grass, 2 sand, 3 mountain, 4 woods, 5 piramid, 7 dirt, 8 lava, 9 water.
local Pajarito = require('pajarito')

--- The weights the examples give to the tileset,
--- a 0 means the tile can not be walked over.
local WEIGHTS = {[1]=1, [2]=3, [3]=0, [4]=2, [5]=0, [7]=1, [8]=0, [9]=0}

local maps = {}

maps.WEIGHTS = WEIGHTS

--- A graph already built and weighted, ready to search.
---@param map number[][]
---@param settings? table extra graph settings, like wrap
---@return Graph
function maps.graphOf(map, settings)
    settings = settings or {}
    settings.type = '2D'
    settings.map = map
    local graph = Pajarito.Graph:new(settings)
    graph:build()
    graph:setWeightMap(WEIGHTS)
    return graph
end

--- Ground with nothing on it, the worst case for anything
--- that has to decide between equally good ways to go.
---@param width number
---@param height number
---@return number[][]
function maps.open(width, height)
    local map = {}
    for y = 1, height do
        map[y] = {}
        for x = 1, width do map[y][x] = 1 end
    end
    return map
end

